# Cross-origin access for the Angular frontend
# -----------------------------------------------------------------------------
# localhost:4200 -> localhost:8000 counts as cross-origin because the ports
# differ. Sessions still work: SameSite is evaluated on the registrable domain,
# and both hosts are `localhost`, so the session cookie is sent along.
#
# In development the Angular dev server also proxies /api to this server, which
# makes the browser treat the calls as same-origin. The settings below are what
# makes direct calls to :8000 work too, and are the base for production.
# -----------------------------------------------------------------------------

CORS_ALLOWED_ORIGINS = [
    'http://localhost:4200',
    'http://127.0.0.1:4200',
]

# Auth lives in a session cookie, so the browser must be allowed to send it.
CORS_ALLOW_CREDENTIALS = True

# Django's CSRF origin check keys off scheme + host + port, so the dev server
# origin has to be listed explicitly for POST /api/auth/login/ to pass.
CSRF_TRUSTED_ORIGINS = [
    'http://localhost:4200',
    'http://127.0.0.1:4200',
]
